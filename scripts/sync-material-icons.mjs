import { createRequire } from "node:module"
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { generateManifest } from "material-icon-theme"

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const packageRoot = path.dirname(require.resolve("material-icon-theme/package.json"))
const manifest = generateManifest()
const output = path.join(root, "apps/ui/public/file-icons")
await mkdir(output, { recursive: true })

// Generate once when updating the dependency. The renderer only reads local
// SVGs and a compact association table; it never loads the extension runtime.
const icons = {}
for (const [id, definition] of Object.entries(manifest.iconDefinitions)) {
  const source = path.resolve(packageRoot, "dist", definition.iconPath)
  const name = path.basename(source)
  icons[id] = name
  await copyFile(source, path.join(output, name))
}
const expanded = { [manifest.folder]: manifest.folderExpanded }
for (const [name, id] of Object.entries(manifest.folderNames)) {
  const open = manifest.folderNamesExpanded[name]
  if (expanded[id] && expanded[id] !== open) throw new Error(`Conflicting expanded folder: ${id}`)
  expanded[id] = open
}
const packageJson = JSON.parse(await readFile(path.join(packageRoot, "package.json"), "utf8"))
const data = {
  version: packageJson.version,
  file: manifest.file,
  folder: manifest.folder,
  rootFolder: manifest.rootFolder,
  rootFolderExpanded: manifest.rootFolderExpanded,
  icons,
  fileNames: manifest.fileNames,
  fileExtensions: manifest.fileExtensions,
  folderNames: manifest.folderNames,
  folderExpanded: expanded,
}
await writeFile(path.join(root, "apps/ui/src/lib/material-icon-theme.generated.json"), JSON.stringify(data, null, 2) + "\n")
const lightIcons = new Map()
for (const [kind, associations] of Object.entries(manifest.light)) {
  for (const [name, lightId] of Object.entries(associations)) {
    const defaultId = manifest[kind]?.[name]
    if (defaultId && defaultId !== lightId) lightIcons.set(icons[defaultId], icons[lightId])
  }
}
// CSS follows the app's theme class, including changes made without rerendering
// a file row. Only icons with an official light variant receive a replacement.
const lightCss = [...lightIcons].map(([dark, light]) =>
  `:root.light img[src$="/file-icons/${dark}"] { content: url("/file-icons/${light}"); }`
).join("\n")
await writeFile(path.join(root, "apps/ui/src/lib/material-icon-theme.generated.css"), `/* Generated by npm run icons:sync. */\n${lightCss}\n`)
await copyFile(path.join(packageRoot, "LICENSE"), path.join(output, "LICENSE.material-icon-theme.txt"))
await writeFile(path.join(output, "README.md"), `Icons and associations from Material Icon Theme ${packageJson.version} (MIT).\nhttps://github.com/material-extensions/vscode-material-icon-theme\n\nUpdate with npm run icons:sync after changing the pinned dependency.\n`)
console.log(`Material Icon Theme ${packageJson.version}: ${Object.keys(icons).length} local icons`)
